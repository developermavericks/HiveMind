// Writes schema.sql: the PostgreSQL version of the database, generated from the SQLite definitions so nothing is copied by hand.
//
//   node deploy/postgres/make-schema.mjs [path-to-sqlite.db]        (default data/hivemind.db)  ->  deploy/postgres/schema.sql
//
// Rules (the SQLite schema only uses INTEGER, TEXT and REAL):
//   INTEGER   -> bigint     (most are millisecond timestamps, which do not fit in 32 bits)
//   REAL      -> double precision
//   TEXT      -> text       (JSON columns stay text for now, so the application code keeps working unchanged; jsonb is a later step)
//   INTEGER PRIMARY KEY AUTOINCREMENT -> bigint GENERATED BY DEFAULT AS IDENTITY   (BY DEFAULT, so existing ids can be copied across)
// Indexes are copied as they are. Nothing else in the definitions needs translating.
import { DatabaseSync } from "node:sqlite";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const dbPath = process.argv[2] || join(here, "..", "..", "data", "hivemind.db");
const db = new DatabaseSync(dbPath, { readOnly: true });
const objs = db.prepare("SELECT type, name, tbl_name, sql FROM sqlite_master WHERE name NOT LIKE 'sqlite_%' AND sql IS NOT NULL ORDER BY (type = 'index'), name").all();

const tidy = (sql) => sql.replace(/\s+/g, " ").trim();
const q = (s) => `"${s}"`;
function table(sql) {
  let s = tidy(sql);
  s = s.replace(/\bINTEGER PRIMARY KEY AUTOINCREMENT\b/gi, "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY");
  s = s.replace(/\bINTEGER\b/gi, "bigint").replace(/\bREAL\b/gi, "double precision").replace(/\bTEXT\b/gi, "text");
  s = s.replace(/CREATE TABLE (IF NOT EXISTS )?(\w+)/i, (_, ine, n) => `CREATE TABLE IF NOT EXISTS ${q(n)}`);
  // one column per line, for people who will read and review it
  const open = s.indexOf("("), body = s.slice(open + 1, s.lastIndexOf(")"));
  const parts = []; let depth = 0, cur = "";
  for (const ch of body) { if (ch === "(") depth++; if (ch === ")") depth--; if (ch === "," && depth === 0) { parts.push(cur.trim()); cur = ""; } else cur += ch; }
  parts.push(cur.trim());
  const cols = parts.map((p) => (/^(PRIMARY KEY|UNIQUE|CHECK|FOREIGN KEY)\b/i.test(p) ? p : p.replace(/^(\w+)/, (m) => q(m))));
  return `${s.slice(0, open + 1)}\n  ${cols.join(",\n  ")}\n);`;
}
function index(sql) {
  return tidy(sql).replace(/CREATE (UNIQUE )?INDEX (IF NOT EXISTS )?(\w+) ON (\w+)\s*\(([^)]*)\)/i, (_, u, ine, name, tbl, cols) => `CREATE ${u ?? ""}INDEX IF NOT EXISTS ${q(name)} ON ${q(tbl)} (${cols.split(",").map((c) => c.trim().replace(/^(\w+)/, (m) => q(m))).join(", ")})`) + ";";
}

const tables = objs.filter((o) => o.type === "table"), indexes = objs.filter((o) => o.type === "index");
let out = `-- HiveMind on PostgreSQL. GENERATED by deploy/postgres/make-schema.mjs from the SQLite database: edit that script, not this file.
-- ${tables.length} tables, ${indexes.length} indexes. Safe to run more than once.
`;
for (const t of tables) out += `\n${table(t.sql)}\n`;
out += "\n-- indexes\n" + indexes.map((i) => index(i.sql)).join("\n") + "\n";
// the copy script sets each identity column to follow the highest copied id; this keeps them listed in one place
out += `\n-- tables with an identity column (the migration script resets their counters after copying)\n-- ${tables.filter((t) => /AUTOINCREMENT/i.test(t.sql)).map((t) => t.name).join(", ")}\n`;
writeFileSync(join(here, "schema.sql"), out);
console.log(`schema.sql written: ${tables.length} tables, ${indexes.length} indexes`);
